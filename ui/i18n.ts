export type Key = keyof typeof zh;
let current: "zh-CN" | "en" = navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";

export function setLang(l: string) {
  current = l === "en" ? "en" : "zh-CN";
  document.documentElement.lang = current;
}
export function lang() {
  return current;
}
export function t(k: Key, args: Record<string, string | number> = {}): string {
  let s: string = (current === "en" ? en : zh)[k] ?? k;
  for (const [a, v] of Object.entries(args)) s = s.replace(`{${a}}`, String(v));
  return s;
}
export function has(k: string): k is Key {
  return k in zh;
}
export function ago(ts: number): string {
  if (!ts) return t("status.never");
  const s = Date.now() / 1000 - ts;
  if (s < 60) return t("time.just");
  if (s < 3600) return t("time.min", { n: Math.floor(s / 60) });
  if (s < 86400) return t("time.hour", { n: Math.floor(s / 3600) });
  return t("time.day", { n: Math.floor(s / 86400) });
}
